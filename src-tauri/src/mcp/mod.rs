/// Build MCP response from session output.
fn build_mcp_response(output: SessionOutput) -> CallToolResult {
    let text = if output.text.is_empty() {
        "=== REVIEW SESSION COMPLETE ===\nBrowser session closed.\nUser completed review without adding annotations.\n".to_string()
    } else {
        format!(
            "=== REVIEW SESSION COMPLETE ===\nBrowser session closed. All annotations are shown below.\n\n{}",
            output.text
        )
    };

    let mut contents = vec![Content::text(text)];

    // Add images as separate content items (data is already base64-encoded)
    for img in output.images {
        contents.push(Content::image(img.data, img.mime_type));
    }

    CallToolResult::success(contents)
}

/// Run the MCP server on stdio.
pub fn run_mcp_server(app_handle: AppHandle) {
    let rt = tokio::runtime::Runtime::new().expect("Failed to create tokio runtime");

    rt.block_on(async {
        let server = AnnotServer::new(app_handle);
        let service = server.serve(rmcp::transport::stdio()).await;
        match service {
            Ok(s) => {
                if let Err(e) = s.waiting().await {
                    eprintln!("MCP server error: {}", e);
                }
            }
            Err(e) => {
                eprintln!("Failed to start MCP server: {}", e);
            }
        }
    });
}

/// Run MCP server in a background thread with panic handling.
pub fn spawn_mcp_thread(app_handle: AppHandle) {
    std::thread::spawn(move || {
        if let Err(e) = std::panic::catch_unwind(AssertUnwindSafe(|| {
            run_mcp_server(app_handle);
        })) {
            eprintln!("MCP server panicked: {:?}", e);
            std::process::exit(1);
        }
    });
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn resolve_root_defaults_to_process_cwd() {
        assert_eq!(resolve_root(None).unwrap(), crate::state::process_cwd());
    }

    #[test]
    fn resolve_root_accepts_a_supplied_directory() {
        let dir = tempfile::tempdir().unwrap();
        let resolved = resolve_root(Some(dir.path().to_str().unwrap())).unwrap();
        assert_eq!(resolved, std::fs::canonicalize(dir.path()).unwrap());
    }

    #[test]
    fn resolve_root_accepts_a_subdirectory_of_a_repo() {
        // Discovery walks upward in both tiers, so pointing at a nested
        // directory is legal — the docstring promises it.
        let dir = tempfile::tempdir().unwrap();
        let nested = dir.path().join("src").join("deep");
        std::fs::create_dir_all(&nested).unwrap();
        let resolved = resolve_root(Some(nested.to_str().unwrap())).unwrap();
        assert_eq!(resolved, std::fs::canonicalize(&nested).unwrap());
    }

    #[test]
    fn resolve_root_rejects_a_missing_directory_naming_it() {
        let err = resolve_root(Some("/definitely/not/a/real/repo")).unwrap_err();
        assert!(
            err.contains("/definitely/not/a/real/repo"),
            "error must quote the caller's own path, got: {err}"
        );
    }

    #[test]
    fn resolve_root_rejects_a_file() {
        let dir = tempfile::tempdir().unwrap();
        let file = dir.path().join("notes.md");
        std::fs::write(&file, "hi").unwrap();
        let err = resolve_root(Some(file.to_str().unwrap())).unwrap_err();
        assert!(err.contains("not a directory"), "got: {err}");
    }
}
